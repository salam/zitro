#!/bin/bash

# Icon Conversion Script for Arduino M5Stick
# Converts PNG icons to bitmap arrays in a separate .ino file

OUTPUT_FILE="icons.ino"
TEMP_PY="convert_icons_temp.py"

echo "Converting PNG icons to Arduino bitmaps..."

# Create Python script for conversion
cat > "$TEMP_PY" << 'PYTHON_SCRIPT'
from PIL import Image
import sys
import os

def convert_png_to_bitmap(filename, var_name):
    """Convert a PNG file to Arduino bitmap array"""
    if not os.path.exists(filename):
        print(f"Warning: {filename} not found, skipping...")
        return None

    img = Image.open(filename).convert('L')
    width, height = img.size

    threshold = 128
    bitmap = []

    for y in range(height):
        row_bytes = []
        for byte_x in range((width + 7) // 8):
            byte_val = 0
            for bit in range(8):
                x = byte_x * 8 + bit
                if x < width:
                    pixel = img.getpixel((x, y))
                    if pixel > threshold:
                        byte_val |= (1 << (7 - bit))
            row_bytes.append(byte_val)
        bitmap.extend(row_bytes)

    bytes_per_row = (width + 7) // 8
    total_bytes = len(bitmap)

    output = []
    output.append(f"// {var_name} from {filename} ({width}x{height} pixels)")
    output.append(f"const uint8_t {var_name}[{total_bytes}] PROGMEM = {{")

    for i in range(0, total_bytes, bytes_per_row):
        row = bitmap[i:i+bytes_per_row]
        hex_vals = ', '.join(f'0x{b:02X}' for b in row)
        output.append(f"  {hex_vals},")

    output.append("};")
    output.append(f"#define {var_name.upper()}_WIDTH {width}")
    output.append(f"#define {var_name.upper()}_HEIGHT {height}")

    return '\n'.join(output), width, height

# Icon definitions: (filename, variable_name, description)
icons = [
    ('mic_icon_20.png', 'micIcon', 'Microphone icon for recording'),
    ('process_icon_20.png', 'transcribeIcon', 'Process/Chart icon for transcribing'),
    ('robot_icon_20.png', 'thinkingIcon', 'Robot/AI icon for thinking'),
    ('voice_icon_20.png', 'voiceIcon', 'Voice/Sound icon for playback indicator'),
    ('rotate_icon_20.png', 'rotateIcon', 'Rotate/Refresh icon for device orientation'),
    ('night_icon_20.png', 'nightIcon', 'Night/Sleep icon for parental control sleep mode'),
    ('generate_icon_20.png', 'generateIcon', 'Generate/Draw icon for image creation'),
    ('print_icon_20.png', 'printIcon', 'Printer icon for the print screens'),
    ('timer_icon_20.png', 'timerIcon', 'Stopwatch icon for the timer list'),
    ('bell_icon_20.png', 'bellIcon', 'Bell icon for the timer alert'),
    ('shake_icon_20.png', 'shakeIcon', 'Shake icon for the home screen hint'),
    ('volume_icon_20.png', 'volumeIcon', 'Speaker icon for volume changes'),
    ('mic_broken_icon_20.png', 'micBrokenIcon', 'Broken microphone icon for mic errors'),
]

output_lines = []
output_lines.append("// Auto-generated icon bitmaps")
output_lines.append("// Generated by convert_icons.sh")
output_lines.append("// DO NOT EDIT MANUALLY - Edit source PNG files and re-run script")
output_lines.append("")

icon_info = []

for filename, var_name, description in icons:
    result = convert_png_to_bitmap(filename, var_name)
    if result:
        bitmap_code, width, height = result
        output_lines.append("")
        output_lines.append(f"// {description}")
        output_lines.append(bitmap_code)
        icon_info.append((var_name, width, height, description))

# Print the code
print('\n'.join(output_lines))

# Print summary to stderr so it doesn't mix with output
sys.stderr.write(f"\nConverted {len(icon_info)} icons successfully:\n")
for var_name, width, height, desc in icon_info:
    sys.stderr.write(f"  - {var_name}: {width}x{height} ({desc})\n")
PYTHON_SCRIPT

# Run Python script and save output (keep stderr separate for status messages)
if python3 "$TEMP_PY" > "$OUTPUT_FILE"; then
    echo "Success! Generated $OUTPUT_FILE"
    echo ""
    echo "File size: $(wc -c < "$OUTPUT_FILE") bytes"
    echo "Lines: $(wc -l < "$OUTPUT_FILE") lines"
    echo ""
    echo "To use in your sketch:"
    echo "  1. Place $OUTPUT_FILE in the same folder as your .ino file"
    echo "  2. Arduino IDE will automatically compile it"
    echo "  3. Access icons using: micIcon, transcribeIcon, thinkingIcon, voiceIcon"
else
    echo "Error during conversion. Check that:"
    echo "  - Python 3 and PIL/Pillow are installed (pip3 install Pillow)"
    echo "  - PNG files exist in the current directory"
    exit 1
fi

# Clean up temp file
rm -f "$TEMP_PY"

echo ""
echo "Done! You can now re-run this script whenever you update the PNG files."
