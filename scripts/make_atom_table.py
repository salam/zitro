#!/usr/bin/env python3
"""Generates sketch/sketch_jan12a/atom_table.h from PubChem's periodic table:
element symbols and atom colours (CPK) as RGB565, indexed by atomic number."""
import json
import pathlib
import subprocess

URL = "https://pubchem.ncbi.nlm.nih.gov/rest/pug/periodictable/JSON"
OUT = pathlib.Path(__file__).resolve().parent.parent / "sketch/sketch_jan12a/atom_table.h"

# curl uses the system's certificate store
raw = subprocess.run(["curl", "-fsS", "-m", "30", "-A", "Zitro", URL], check=True, capture_output=True).stdout
table = json.loads(raw)["Table"]
cols = table["Columns"]["Column"]
number, symbol, cpk = cols.index("AtomicNumber"), cols.index("Symbol"), cols.index("CPKHexColor")
rows = sorted((int(row["Cell"][number]), row["Cell"][symbol], row["Cell"][cpk]) for row in table["Row"])
assert [r[0] for r in rows] == list(range(1, len(rows) + 1))


def rgb565(hex_colour):
    # PubChem leaves a few heavy elements without a colour: use a neutral grey
    value = int(hex_colour or "A0A0A0", 16)
    r, g, b = value >> 16, (value >> 8) & 255, value & 255
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


lines = ["// Generated by scripts/make_atom_table.py from PubChem's periodic table. Do not edit.",
         "#pragma once", "", "#include <stdint.h>", "",
         f"#define ATOM_TABLE_SIZE {len(rows) + 1}", "",
         "// Index is the atomic number; entry 0 is unused.",
         "static const char ATOM_SYMBOLS[ATOM_TABLE_SIZE][3] = {", '  "",']
lines += [f'  "{s}",' for _, s, _ in rows]
lines += ["};", "", "static const uint16_t ATOM_COLORS[ATOM_TABLE_SIZE] = {", "  0x0000,"]
lines += [f"  0x{rgb565(c):04X},  // {s}" for _, s, c in rows]
lines += ["};", ""]
OUT.write_text("\n".join(lines))
print(f"{OUT.name}: {len(rows)} elements")
