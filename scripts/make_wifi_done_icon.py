#!/usr/bin/env python3
"""Make the "connected" corner icon: a WiFi symbol with a green tick, for sketch/sketch_jan12a.

Material Symbols has no WiFi-with-tick icon, so this puts two of its Rounded icons (weight 400)
together the way Material puts a badge on an icon (wifi_add, wifi_lock): "wifi" in white and a
filled "check_circle" in green in its bottom right corner, with a thin black ring cut around it.
Rendered with anti-aliased edges over black, at full brightness; the firmware scales it down to fade.

Writes sketch/sketch_jan12a/wifi_done_icon.h. With --preview FILE, also a PNG at 8x to look at.

Usage: python3 scripts/make_wifi_done_icon.py [--preview FILE]

Needs rsvg-convert (brew install librsvg) and Pillow.
"""
import argparse
import io
import subprocess
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
HEADER = ROOT / "sketch" / "sketch_jan12a" / "wifi_done_icon.h"

# Material Symbols by Google, Apache License 2.0: https://github.com/google/material-design-icons
# symbols/web/wifi/materialsymbolsrounded/wifi_24px.svg (viewBox 0 -960 960 960)
WIFI = (
    "M480-120q-42 0-71-29t-29-71q0-42 29-71t71-29q42 0 71 29t29 71q0 42-29 71t-71 29Zm0-440q75 0 "
    "142.5 24T745-470q20 15 20.5 39.5T748-388q-17 17-42 17.5T661-384q-38-26-84-41t-97-15q-51 0-97 "
    "15t-84 41q-20 14-45 13t-42-18q-17-18-17-42.5t20-39.5q55-42 122.5-65.5T480-560Zm0-240q125 0 "
    "235.5 41T914-643q20 17 21 42t-17 43q-17 17-42 17.5T831-556q-72-59-161.5-91.5T480-680q-100 "
    "0-189.5 32.5T129-556q-20 16-45 15.5T42-558q-18-18-17-43t21-42q88-75 198.5-116T480-800Z"
)
# symbols/web/check_circle/materialsymbolsrounded/check_circle_fill1_24px.svg
CHECK_CIRCLE = (
    "m424-408-86-86q-11-11-28-11t-28 11q-11 11-11 28t11 28l114 114q12 12 28 12t28-12l226-226q11-11 "
    "11-28t-11-28q-11-11-28-11t-28 11L424-408Zm56 328q-83 0-156-31.5T197-197q-54-54-85.5-127T80-480q0-83 "
    "31.5-156T197-763q54-54 127-85.5T480-880q83 0 156 31.5T763-763q54 54 85.5 127T880-480q0 83-31.5 "
    "156T763-197q-54 54-127 85.5T480-80Z"
)
WIFI_BOX = (25, -800, 935, -120)   # where the wifi glyph's ink lies in its 960 grid
CIRCLE = (480, -480, 400)          # check_circle's disc: centre and radius in its grid

# The icon, in pixels
W, H = 23, 18
WIFI_WIDTH = 18.0     # the wifi glyph, about as wide as the searching icon (17 px)
WIFI_AT = (0.5, 1.0)  # its top left
BADGE = (18.0, 13.0, 4.5)  # the tick's disc: centre and radius
RING = 1.0            # black cut between the disc and the glyph
GREEN = (0x00, 0xE6, 0x76)  # Material green A400
WHITE = (0xFF, 0xFF, 0xFF)


def svg(body):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}">'
            f'{body}</svg>')


def alpha(doc):
    png = subprocess.run(["rsvg-convert", "-f", "png"], input=doc.encode(), capture_output=True,
                         check=True).stdout
    return Image.open(io.BytesIO(png)).convert("RGBA").getchannel("A")


def render():
    x0, y0, x1, _ = WIFI_BOX
    s = WIFI_WIDTH / (x1 - x0)
    wifi = (f'<path transform="translate({WIFI_AT[0]} {WIFI_AT[1]}) scale({s}) translate({-x0} {-y0})" '
            f'd="{WIFI}"/>')
    bx, by, br = BADGE
    cx, cy, cr = CIRCLE
    badge = (f'<path transform="translate({bx} {by}) scale({br / cr}) translate({-cx} {-cy})" '
             f'd="{CHECK_CIRCLE}"/>')
    cut = (f'<mask id="cut"><rect width="{W}" height="{H}" fill="white"/>'
           f'<circle cx="{bx}" cy="{by}" r="{br + RING}" fill="black"/></mask>')
    white = alpha(svg(f'<defs>{cut}</defs><g mask="url(#cut)" fill="white">{wifi}</g>'))
    green = alpha(svg(f'<g fill="white">{badge}</g>'))
    img = Image.new("RGB", (W, H))
    for y in range(H):
        for x in range(W):
            a_w = white.getpixel((x, y)) / 255
            a_g = green.getpixel((x, y)) / 255
            img.putpixel((x, y), tuple(round(w * a_w * (1 - a_g) + g * a_g) for w, g in zip(WHITE, GREEN)))
    return img


def write_header(img):
    rows = []
    for y in range(H):
        row = []
        for x in range(W):
            row.extend(img.getpixel((x, y)))
        rows.append("  " + ", ".join(f"0x{v:02X}" for v in row) + ",")
    HEADER.write_text(
        "// The connected icon: Material Symbols' \"wifi\" in white with a green \"check_circle\" badge,\n"
        "// RGB888 over black at full brightness. Drawn by wifi_link.ino, which scales it to fade.\n"
        "// Generated by scripts/make_wifi_done_icon.py - DO NOT EDIT MANUALLY, run the script.\n"
        "// Material Symbols (Rounded, weight 400) by Google, Apache License 2.0.\n"
        "#pragma once\n"
        "#include <stdint.h>\n\n"
        f"static const int WIFI_DONE_W = {W};\n"
        f"static const int WIFI_DONE_H = {H};\n\n"
        f"static const uint8_t wifiDoneIcon[{W * H * 3}] PROGMEM = {{\n"
        + "\n".join(rows)
        + "\n};\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--preview", type=Path, help="also write the icon at 8x to this PNG")
    args = parser.parse_args()
    img = render()
    write_header(img)
    print(f"wrote {HEADER.relative_to(ROOT)} ({W}x{H})")
    if args.preview:
        img.resize((W * 8, H * 8), Image.NEAREST).save(args.preview)
        print(f"wrote {args.preview}")


if __name__ == "__main__":
    main()
