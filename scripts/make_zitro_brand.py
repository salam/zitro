#!/usr/bin/env python3
"""Generate Zitro brand assets for the device and installer.

Outputs:
  designs/zitro-splash.png               240x135 boot splash (device screen size), wordmark on black
  designs/zitro-app-icon.png             1024x1024 app icon
  sketch/sketch_jan12a/logo_data.h       splash as PNG byte array for the firmware

Palette and type follow webpage2/styles.css (zitro.spot): warm paper, graphite ink,
one citrus accent, Sniglet display face (fonts/Sniglet-*.ttf, SIL OFL).

Usage: python3 scripts/make_zitro_brand.py
"""
import io
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
PAPER = (244, 239, 230)    # --paper
INK = (43, 39, 33)         # --ink
INK_SOFT = (107, 100, 89)  # --ink-soft
CITRUS = (242, 183, 5)     # --citrus
SPOT_ON_BLACK = (168, 160, 147)  # ink-soft lifted for a black background

BOLD = str(ROOT / "fonts" / "Sniglet-ExtraBold.ttf")
REGULAR = str(ROOT / "fonts" / "Sniglet-Regular.ttf")


def draw_wordmark(draw, center_x, baseline_y, size, colors=(INK, CITRUS, INK_SOFT)):
    """Draw 'zitro.spot' centered on center_x (colors: zitro, dot, spot)."""
    bold = ImageFont.truetype(BOLD, size)
    regular = ImageFont.truetype(REGULAR, size)
    parts = [("zitro", bold, colors[0]), (".", bold, colors[1]), ("spot", regular, colors[2])]
    widths = [draw.textlength(text, font=font) for text, font, _ in parts]
    x = center_x - sum(widths) / 2
    for (text, font, color), width in zip(parts, widths):
        draw.text((x, baseline_y), text, font=font, fill=color, anchor="ls")
        x += width


SPLASH_PADDING_X = 24  # Breathing room so the wordmark doesn't run to the screen edges


def make_splash():
    """Boot splash: the wordmark alone on black, in paper tones so it reads on the LCD."""
    w, h = 240, 135
    colors = (PAPER, CITRUS, SPOT_ON_BLACK)
    # Largest size whose wordmark fits inside the horizontal padding
    size = 44
    while size > 10:
        probe = Image.new("RGB", (w * 2, h), (0, 0, 0))
        draw_wordmark(ImageDraw.Draw(probe), w, 80, size, colors=colors)
        left, top, right, bottom = probe.getbbox()
        if right - left <= w - 2 * SPLASH_PADDING_X:
            break
        size -= 1
    # Center the drawn ink vertically
    baseline = 80 + round(h / 2 - (top + bottom) / 2)
    img = Image.new("RGB", (w, h), (0, 0, 0))
    draw_wordmark(ImageDraw.Draw(img), w / 2, baseline, size, colors=colors)
    return img


def make_app_icon():
    size = 1024
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)
    draw.rounded_rectangle((0, 0, size - 1, size - 1), radius=230, fill=PAPER + (255,))
    font = ImageFont.truetype(BOLD, 640)
    z_width = draw.textlength("z", font=font)
    dot_r = 62
    x = (size - z_width - dot_r * 2.4) / 2
    draw.text((x, 700), "z", font=font, fill=INK, anchor="ls")
    cx = x + z_width + dot_r * 1.3
    draw.ellipse((cx - dot_r, 700 - dot_r * 2, cx + dot_r, 700), fill=CITRUS)
    return img


def write_header(png_bytes, path):
    lines = [
        "// Zitro boot splash (zitro.spot)",
        "// Auto-generated by scripts/make_zitro_brand.py from designs/zitro-splash.png",
        "// Indexed PNG stored in flash (PROGMEM)",
        "",
        "const unsigned char logo_png[] PROGMEM = {",
    ]
    for i in range(0, len(png_bytes), 12):
        chunk = png_bytes[i:i + 12]
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    lines += [
        "};",
        "const unsigned int logo_png_len = sizeof(logo_png);",
        "",
        "#define LOGO_WIDTH 240",
        "#define LOGO_HEIGHT 135",
        "",
    ]
    path.write_text("\n".join(lines))


def main():
    splash = make_splash()
    splash.save(ROOT / "designs" / "zitro-splash.png")
    make_app_icon().save(ROOT / "designs" / "zitro-app-icon.png")

    # Indexed colors keep the firmware asset small
    buf = io.BytesIO()
    splash.quantize(colors=64, method=Image.Quantize.MEDIANCUT).save(buf, format="PNG", optimize=True)
    png = buf.getvalue()
    write_header(png, ROOT / "sketch" / "sketch_jan12a" / "logo_data.h")
    print(f"Splash PNG: {len(png)} bytes -> sketch/sketch_jan12a/logo_data.h")


if __name__ == "__main__":
    main()
