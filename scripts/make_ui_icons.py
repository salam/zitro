def main():
    for name, rows in ICONS.items():
        assert len(rows) == 20 and all(len(r) == 20 for r in rows), name
        img = Image.new("L", (20, 20), 0)
        for y, row in enumerate(rows):
            for x, ch in enumerate(row):
                if ch == "#":
                    img.putpixel((x, y), 255)
        img.save(ROOT / name)
        print(f"wrote {name}")


if __name__ == "__main__":
    main()
