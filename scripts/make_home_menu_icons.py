#!/usr/bin/env python3
"""Make the home menu's row icons: one 20x20 Material Symbol per row, for sketch/sketch_jan12a.

Matthias, 2026-11-16: "Das Menü sollte statt dem ⏵ triangle auch Icons haben für Settings (Zahnräder), Timer
(Timer-Uhr), Tour, Überraschung (Päckli). Stretch goal: für Orion, etc. auch."

Each icon is Material Symbols Rounded (weight 400, 24 px design), rendered 4x larger and box-filtered down to 20x20,
kept as coverage (0 = nothing, 255 = full). The firmware draws it in the row's ink: white on black, black on the
selected white row, as the ▶ before it.

Writes sketch/sketch_jan12a/home_menu_icons.h. With --preview FILE, also a PNG of all icons at 4x to look at.

Usage: python3 scripts/make_home_menu_icons.py [--preview FILE] [--cache DIR]

Needs rsvg-convert (brew install librsvg), Pillow, and the network the first time (the SVGs are cached).
"""
import argparse
import io
import os
import subprocess
import tempfile
import urllib.request
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
HEADER = ROOT / "sketch" / "sketch_jan12a" / "home_menu_icons.h"
SIZE = 20
OVERSAMPLE = 4

# Material Symbols by Google, Apache License 2.0: https://github.com/google/material-design-icons
URL = "https://raw.githubusercontent.com/google/material-design-icons/master/symbols/web/{0}/materialsymbolsrounded/{0}_24px.svg"

# In the home menu's row order (home_menu_core.h): the 6 functions, then the 16 questions
ROWS = [
    ("Timer anzeigen", "timer"),
    ("Tour starten", "tour"),
    ("Überraschung", "featured_seasonal_and_gifts"),
    ("Wörter üben", "translate"),
    ("Einstellungen", "settings"),
    ("Menü schliessen", "close"),
    ("Wo ist Orion?", "star"),
    ("Wo ist die ISS?", "satellite_alt"),
    ("Mondlandungen", "rocket_launch"),
    ("Mondphasen", "dark_mode"),
    ("Foto: Marie Curie", "photo_camera"),
    ("T-Rex", "trex"),
    ("Das Herz", "cardiology"),
    ("DNA in 3D", "genetics"),
    ("Salzkristall", "diamond"),
    ("Wassermolekül", "water_drop"),
    ("Ikosaeder", "icosahedron"),
    ("Kurve von x²", "parabola"),
    ("Matterhorn", "landscape"),
    ("Uhrzeit in Tokio", "schedule"),
    ("Pfannkuchen", "skillet"),
    ("Twinkle Twinkle", "music_note"),
]


# Drawn here where Material Symbols has nothing that fits, in its 24 px grid and its 2 px line weight
STROKE = 'fill="none" stroke="black" stroke-linecap="round" stroke-linejoin="round"'
OWN = {
    # A Tyrannosaurus side on, facing right: tail, back, big head, small arm, two legs
    "trex": '<path fill="black" d="M1 8.5 L6 9 L10 8 L12.5 6 L13.5 3 L21 3 L22.5 4.5 L22.5 6.5 L18.5 6.8 L21.5 8 '
            'L20.5 9.6 L16.5 10 L15.5 11.8 L17.6 12.8 L17.4 14 L15.2 13.4 L14.4 15 L13.4 17 L14.6 20.6 L16.4 21.6 '
            'L16.2 22.6 L12.2 22.6 L11.2 18.4 L9.6 18.4 L9.8 21.2 L11 22 L10.8 22.6 L7.2 22.6 L7 16.4 L5 13.2 Z"/>',
    # y = x^2 on two axes
    "parabola": f'<path {STROKE} stroke-width="1.3" d="M12 2.5 V21.5 M2.5 18 H21.5"/>'
                f'<path {STROKE} stroke-width="2.2" d="M3.5 4 Q12 31.5 20.5 4"/>',
    # An icosahedron as it looks along an axis through two corners: a hexagon round a triangle
    "icosahedron": f'<path {STROKE} stroke-width="1.6" d="M12 2.5 L20.2 7.2 L20.2 16.8 L12 21.5 L3.8 16.8 L3.8 7.2 Z '
                   'M12 8 L16.2 15.2 L7.8 15.2 Z M12 8 L12 2.5 M12 8 L20.2 7.2 M12 8 L3.8 7.2 '
                   'M16.2 15.2 L20.2 7.2 M16.2 15.2 L20.2 16.8 M16.2 15.2 L12 21.5 '
                   'M7.8 15.2 L12 21.5 M7.8 15.2 L3.8 16.8 M7.8 15.2 L3.8 7.2"/>',
}


def fetch(name, cache):
    if name in OWN:
        return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">{OWN[name]}</svg>'.encode()
    path = cache / f"{name}.svg"
    if not path.exists():
        with urllib.request.urlopen(URL.format(name), timeout=30) as r:
            path.write_bytes(r.read())
    return path.read_bytes()


def coverage(svg):
    big = SIZE * OVERSAMPLE
    png = subprocess.run(["rsvg-convert", "-w", str(big), "-h", str(big)], input=svg, capture_output=True,
                         check=True).stdout
    alpha = Image.open(io.BytesIO(png)).convert("RGBA").getchannel("A")
    return alpha.resize((SIZE, SIZE), Image.BOX)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview")
    ap.add_argument("--cache", default=os.path.join(tempfile.gettempdir(), "zitro_material_symbols"))
    args = ap.parse_args()
    cache = Path(args.cache)
    cache.mkdir(parents=True, exist_ok=True)

    icons = [(label, name, coverage(fetch(name, cache))) for label, name in ROWS]

    out = [
        "// The home menu's row icons, 20x20 coverage (0 nothing .. 255 full), drawn in the row's ink.",
        "// Generated by scripts/make_home_menu_icons.py - edit the list there and run it again.",
        "// Material Symbols Rounded by Google, Apache License 2.0: https://github.com/google/material-design-icons",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        f"static const int HOME_ICON_SIZE = {SIZE};",
        "",
    ]
    for label, name, img in icons:
        data = list(img.get_flattened_data()) if hasattr(img, 'get_flattened_data') else list(img.getdata())
        out.append(f"// {label}: {name}")
        out.append(f"static const uint8_t HOME_ICON_{name.upper()}[{SIZE * SIZE}] = {{")
        for y in range(SIZE):
            out.append("  " + ", ".join(f"{v:3d}" for v in data[y * SIZE:(y + 1) * SIZE]) + ",")
        out.append("};")
        out.append("")
    out.append("// One icon per row, in the menu's order: the 6 functions, then the 16 questions")
    out.append(f"static const uint8_t* const HOME_ROW_ICONS[{len(icons)}] = {{")
    for _, name, _ in icons:
        out.append(f"  HOME_ICON_{name.upper()},")
    out.append("};")
    out.append(f"static const char* const HOME_ROW_ICON_NAMES[{len(icons)}] = {{")
    for _, name, _ in icons:
        out.append(f'  "{name}",')
    out.append("};")
    HEADER.write_text("\n".join(out) + "\n")
    print(f"wrote {HEADER.relative_to(ROOT)} ({len(icons)} icons)")

    if args.preview:
        scale, cell = 4, SIZE * 4 + 16
        sheet = Image.new("RGB", (cell * 6, cell * 4), "black")
        for k, (_, _, img) in enumerate(icons):
            x, y = (k % 6) * cell + 8, (k // 6) * cell + 8
            on = k == 0  # the first as the selected row: black on white
            if on:
                ImageDraw.Draw(sheet).rectangle([x - 4, y - 4, x + SIZE * scale + 3, y + SIZE * scale + 3], fill="white")
            big = img.resize((SIZE * scale, SIZE * scale), Image.NEAREST)
            ink = Image.new("RGB", big.size, "black" if on else "white")
            sheet.paste(ink, (x, y), big)
        sheet.save(args.preview)
        print(f"preview {args.preview}")


if __name__ == "__main__":
    main()
