#!/bin/bash

# Build Firebird Installer SwiftUI App

set -e

echo "======================================"
echo "  Building Firebird Installer GUI"
echo "======================================"
echo ""

GUI_DIR="$(cd "$(dirname "$0")" && pwd)"
INSTALLER_DIR="$(dirname "$GUI_DIR")"
APP_NAME="Install Firebird AI Stick"
BUILD_DIR="$GUI_DIR/build"
APP_BUNDLE="$BUILD_DIR/$APP_NAME.app"

# Clean previous build
rm -rf "$BUILD_DIR"
mkdir -p "$BUILD_DIR"

# Create app bundle structure
echo "Creating app bundle structure..."
mkdir -p "$APP_BUNDLE/Contents/MacOS"
mkdir -p "$APP_BUNDLE/Contents/Resources"
mkdir -p "$APP_BUNDLE/Contents/Resources/firmware"

# Generate BuildInfo.swift
echo "Generating build info..."
BUILD_NUMBER=$(date +%Y%m%d%H%M)
BUILD_TIME=$(date '+%Y-%m-%d %H:%M:%S')
cat > "$GUI_DIR/Sources/BuildInfo.swift" << EOF
// Auto-generated by build.sh
import Foundation

struct BuildInfo {
    static let version = "1.0"
    static let buildNumber = "$BUILD_NUMBER"
    static let buildTime = "$BUILD_TIME"
}
EOF
echo "✓ Build info generated: v$BUILD_NUMBER"

# Compile SwiftUI app as universal binary
SDK=$(xcrun --show-sdk-path --sdk macosx)

echo "Compiling SwiftUI application for arm64 (Apple Silicon)..."
swiftc -O \
    -target arm64-apple-macos11.0 \
    -sdk "$SDK" \
    -framework SwiftUI \
    -framework Combine \
    -framework Foundation \
    -framework AppKit \
    "$GUI_DIR"/Sources/*.swift \
    -o "$APP_BUNDLE/Contents/MacOS/${APP_NAME}-arm64"

echo "Compiling SwiftUI application for x86_64 (Intel)..."
swiftc -O \
    -target x86_64-apple-macos11.0 \
    -sdk "$SDK" \
    -framework SwiftUI \
    -framework Combine \
    -framework Foundation \
    -framework AppKit \
    "$GUI_DIR"/Sources/*.swift \
    -o "$APP_BUNDLE/Contents/MacOS/${APP_NAME}-x86_64"

echo "Creating universal binary..."
lipo -create \
    "$APP_BUNDLE/Contents/MacOS/${APP_NAME}-arm64" \
    "$APP_BUNDLE/Contents/MacOS/${APP_NAME}-x86_64" \
    -output "$APP_BUNDLE/Contents/MacOS/$APP_NAME"

# Clean up arch-specific binaries
rm -f "$APP_BUNDLE/Contents/MacOS/${APP_NAME}-arm64" "$APP_BUNDLE/Contents/MacOS/${APP_NAME}-x86_64"

if [ ! -f "$APP_BUNDLE/Contents/MacOS/$APP_NAME" ]; then
    echo "Error: Compilation failed"
    exit 1
fi

echo "✓ Universal binary created (arm64 + x86_64)"

# Copy resources
echo "Copying resources..."

# Copy esp32flash binary
if [ -f "$INSTALLER_DIR/native_flasher/bin/esp32flash" ]; then
    cp "$INSTALLER_DIR/native_flasher/bin/esp32flash" "$APP_BUNDLE/Contents/Resources/"
    chmod +x "$APP_BUNDLE/Contents/Resources/esp32flash"
    echo "✓ Copied esp32flash"
else
    echo "Warning: esp32flash not found, build it first"
fi

# Copy firmware parts
FIRMWARE_COPIED=0
for fw in bootloader.bin partitions.bin boot_app0.bin application.bin; do
    if [ -f "$INSTALLER_DIR/firmware/$fw" ]; then
        cp "$INSTALLER_DIR/firmware/$fw" "$APP_BUNDLE/Contents/Resources/firmware/"
        FIRMWARE_COPIED=$((FIRMWARE_COPIED + 1))
    fi
done
if [ $FIRMWARE_COPIED -gt 0 ]; then
    echo "✓ Copied $FIRMWARE_COPIED firmware parts"
else
    echo "Warning: no firmware parts found"
fi

# Copy app icon if available
if [ -f "$INSTALLER_DIR/assets/AppIcon.icns" ]; then
    cp "$INSTALLER_DIR/assets/AppIcon.icns" "$APP_BUNDLE/Contents/Resources/"
    echo "✓ Copied app icon"
fi

# Copy plug-in image
if [ -f "$INSTALLER_DIR/assets/plug-in.png" ]; then
    cp "$INSTALLER_DIR/assets/plug-in.png" "$APP_BUNDLE/Contents/Resources/"
    echo "✓ Copied plug-in image"
fi

# Create Info.plist
echo "Creating Info.plist..."
cat > "$APP_BUNDLE/Contents/Info.plist" << 'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleExecutable</key>
    <string>Install Firebird AI Stick</string>
    <key>CFBundleIdentifier</key>
    <string>com.firebird.aistick.installer</string>
    <key>CFBundleName</key>
    <string>Install Firebird AI Stick</string>
    <key>CFBundleDisplayName</key>
    <string>Install Firebird AI Stick</string>
    <key>CFBundleIconFile</key>
    <string>AppIcon.icns</string>
    <key>CFBundleShortVersionString</key>
    <string>1.0</string>
    <key>CFBundleVersion</key>
    <string>1</string>
    <key>CFBundlePackageType</key>
    <string>APPL</string>
    <key>LSMinimumSystemVersion</key>
    <string>11.0</string>
    <key>NSHighResolutionCapable</key>
    <true/>
    <key>LSApplicationCategoryType</key>
    <string>public.app-category.developer-tools</string>
    <key>NSHumanReadableCopyright</key>
    <string>Copyright © 2026 Firebird AI Stick</string>
</dict>
</plist>
PLIST

echo "✓ Info.plist created"

# Make executable
chmod +x "$APP_BUNDLE/Contents/MacOS/$APP_NAME"

echo ""
echo "======================================"
echo "✓ Build complete!"
echo "======================================"
echo ""
echo "App bundle: $APP_BUNDLE"
echo ""
echo "To test: open \"$APP_BUNDLE\""
echo ""
