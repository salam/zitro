#!/usr/bin/env python3
"""Generates sketch/sketch_jan12a/physics_atom_table.h: electron shells of hydrogen to krypton.

Input: PubChem's periodic table, https://pubchem.ncbi.nlm.nih.gov/rest/pug/periodictable/JSON
Usage: python3 -I scripts/make_physics_atoms.py <downloaded periodic.json> <output header>

Shells are counted per principal quantum number from PubChem's electron configuration, so
copper's "[Ar]4s1 3d10" gives 2 8 18 1. German names are not in PubChem: they are checked by
hand against Wikipedia's "Liste der chemischen Elemente" (see docs/features/physics.md).
"""
import json
import re
import sys

LAST_ELEMENT = 36
GERMAN = """Wasserstoff Helium Lithium Beryllium Bor Kohlenstoff Stickstoff Sauerstoff Fluor Neon
Natrium Magnesium Aluminium Silicium Phosphor Schwefel Chlor Argon Kalium Calcium Scandium Titan
Vanadium Chrom Mangan Eisen Cobalt Nickel Kupfer Zink Gallium Germanium Arsen Selen Brom Krypton""".split()


def shells_of(config, by_symbol):
    """Electrons per shell from a configuration such as '[Ar]4s2 3d10 4p1'."""
    shells = [0, 0, 0, 0]
    core = re.match(r"\s*\[(\w+)\]", config)
    if core:
        shells = list(by_symbol[core.group(1)])
        config = config[core.end():]
    consumed = 0
    for match in re.finditer(r"([1-4])([spdf])(\d+)", config):
        shells[int(match.group(1)) - 1] += int(match.group(3))
        consumed += len(match.group(0))
    if consumed != len(config.replace(" ", "")):
        raise ValueError("unexpected configuration: " + config)
    return shells


def main():
    table = json.load(open(sys.argv[1], encoding="utf-8"))["Table"]
    columns = table["Columns"]["Column"]
    cell = lambda row, name: row["Cell"][columns.index(name)]
    by_symbol = {}
    lines = []
    for row in table["Row"][:LAST_ELEMENT]:
        number = int(cell(row, "AtomicNumber"))
        symbol, name = cell(row, "Symbol"), cell(row, "Name")
        shells = shells_of(cell(row, "ElectronConfiguration"), by_symbol)
        if sum(shells) != number:
            raise ValueError(f"{symbol}: {shells} does not add up to {number}")
        by_symbol[symbol] = shells
        german = GERMAN[number - 1]
        counts = ", ".join(str(s) for s in shells)
        lines.append(f'    {{"{symbol}", "{name}", "{german}", {{{counts}}}}},')
    with open(sys.argv[2], "w", encoding="ascii") as out:
        out.write("// Electron shells of the first elements. Generated by scripts/make_physics_atoms.py\n")
        out.write("// from PubChem's periodic table; do not edit by hand.\n#pragma once\n\n#include <stdint.h>\n\n")
        out.write("struct PhysicsElement {\n  const char* symbol;\n  const char* en;\n  const char* de;\n  uint8_t shells[4];\n};\n\n")
        out.write("// Index + 1 is the atomic number\nstatic const PhysicsElement PHYSICS_ELEMENTS[] = {\n")
        out.write("\n".join(lines))
        out.write("\n};\nstatic const int PHYSICS_ELEMENT_COUNT = sizeof(PHYSICS_ELEMENTS) / sizeof(PHYSICS_ELEMENTS[0]);\n")


if __name__ == "__main__":
    main()
