#!/usr/bin/env python3
"""Subset the Sniglet display font for the device's setup page.

The setup page is served by the stick in setup mode, without internet, so it can't load
Google Fonts like zitro.spot does. This writes small WOFF2 subsets (Latin + German umlauts)
into sketch/sketch_jan12a/setup_fonts.h; the firmware serves them at /f/sniglet-400.woff2
and /f/sniglet-800.woff2.

Needs: pip install fonttools brotli
Usage: python3 scripts/make_setup_fonts.py
"""
import io
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
UNICODES = list(range(0x20, 0x7F)) + [0xC4, 0xD6, 0xDC, 0xE4, 0xF6, 0xFC, 0xDF, 0x2019, 0x2026]
FONTS = [("sniglet_400", "Sniglet-Regular.ttf"), ("sniglet_800", "Sniglet-ExtraBold.ttf")]


def woff2_subset(path):
    font = TTFont(path)
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = ["kern", "liga"]
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=UNICODES)
    subsetter.subset(font)
    buf = io.BytesIO()
    font.flavor = "woff2"
    font.save(buf)
    return buf.getvalue()


def main():
    lines = [
        "// Sniglet (SIL OFL) subsets for the setup page, served at /f/<name>.woff2",
        "// Auto-generated by scripts/make_setup_fonts.py from fonts/Sniglet-*.ttf",
        "#pragma once",
        "",
    ]
    for name, file in FONTS:
        data = woff2_subset(ROOT / "fonts" / file)
        lines.append(f"const unsigned char {name}_woff2[] PROGMEM = {{")
        for i in range(0, len(data), 16):
            lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
        lines += ["};", f"const unsigned int {name}_woff2_len = sizeof({name}_woff2);", ""]
        print(f"{file}: {len(data)} bytes")
    (ROOT / "sketch" / "sketch_jan12a" / "setup_fonts.h").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
